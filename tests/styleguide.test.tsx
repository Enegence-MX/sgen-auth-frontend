import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { fixture } from './fixtures'
import { render } from './render'

// Canvas rendering is verified in the browser; these tests cover page behavior.
vi.mock('../src/shared/ui/DataChart', () => ({ DataChart: () => null }))

describe('style guide', () => {
  it('opens in Spanish without a language selector and keeps app preferences unchanged', async () => {
    const user = userEvent.setup()
    const setup = fixture()
    const restore = vi.spyOn(setup.services.auth, 'restore')
    const rootClasses = document.documentElement.className
    const { i18n } = render(setup.services, '/styleguide', ['en'])
    await screen.findByRole('heading', { name: 'Guía de estilos', level: 1 })
    expect(restore).not.toHaveBeenCalled()
    expect(document.title).toBe('SGEn | Guía de estilos')
    expect(document.documentElement.lang).toBe('es')
    expect(screen.queryByLabelText('Idioma')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Language')).not.toBeInTheDocument()
    expect(i18n.resolvedLanguage).toBe('en')
    const sidebar = within(screen.getByRole('complementary'))
    expect(sidebar.getByRole('group', { name: 'Tema de la vista previa' })).toBeInTheDocument()
    expect(within(screen.getByRole('banner')).queryByRole('button', { name: 'Oscuro' })).not.toBeInTheDocument()
    await user.click(sidebar.getByRole('button', { name: 'Oscuro' }))
    expect(screen.getByRole('button', { name: 'Oscuro' })).toHaveAttribute('aria-pressed', 'true')
    expect(document.documentElement.className).toBe(rootClasses)
  })

  it('opens the example user menu with keyboard and keeps its actions local', async () => {
    const user = userEvent.setup()
    const setup = fixture()
    const { router } = render(setup.services, '/styleguide')
    const trigger = await screen.findByRole('button', { name: 'Menú de usuario: Lorem Ipsum' })
    trigger.focus()
    await user.keyboard('{ArrowDown}')
    const menu = within(await screen.findByRole('menu'))
    expect(menu.getByText('lorem.ipsum@example.com')).toBeInTheDocument()
    expect(menu.getByText('Dolor sit amet')).toBeInTheDocument()
    expect(menu.getByText('Rol')).toBeInTheDocument()
    await user.keyboard('{Escape}')
    await waitFor(() => expect(trigger).toHaveFocus())
    await user.click(trigger)
    await user.click(await screen.findByRole('menuitem', { name: 'Configuración' }))
    await waitFor(() => expect(screen.queryByRole('menu')).not.toBeInTheDocument())
    expect(screen.getByText('Configuración')).toBeInTheDocument()
    await user.click(trigger)
    await user.click(await screen.findByRole('menuitem', { name: 'Cerrar sesión' }))
    await waitFor(() => expect(screen.queryByRole('menu')).not.toBeInTheDocument())
    expect(screen.getByText('Cerrar sesión')).toBeInTheDocument()
    expect(router.state.location.pathname).toBe('/styleguide')
    expect(setup.fetcher).not.toHaveBeenCalled()
  })

  it('keeps the example form local and resets its feedback and values', async () => {
    const user = userEvent.setup()
    const setup = fixture()
    const create = vi.spyOn(setup.services.organizations, 'create')
    render(setup.services, '/styleguide')
    const form = within(await screen.findByRole('form', { name: 'Formulario' }))
    await user.type(form.getByLabelText('Nombre de la organización'), 'Organización de prueba')
    await user.selectOptions(form.getByLabelText('Nivel de acceso'), 'editor')
    await user.click(form.getByLabelText('Recibir resúmenes de actividad'))
    await user.click(form.getByRole('button', { name: 'Guardar ejemplo' }))
    expect(form.getByRole('status')).toHaveTextContent('Lorem ipsum, Organización de prueba.')
    expect(create).not.toHaveBeenCalled()
    await user.click(form.getByRole('button', { name: 'Restablecer' }))
    expect(form.queryByRole('status')).not.toBeInTheDocument()
    expect(form.getByLabelText('Nombre de la organización')).toHaveValue('')
    expect(form.getByLabelText('Nivel de acceso')).toHaveValue('reader')
    expect(form.getByLabelText('Recibir resúmenes de actividad')).not.toBeChecked()
  })

  it('keeps every section available with expanded and collapsed navigation', async () => {
    const user = userEvent.setup()
    const setup = fixture()
    render(setup.services, '/styleguide')
    const navigation = within(await screen.findByRole('navigation', { name: 'Secciones de la guía' }))
    expect(screen.queryByRole('searchbox', { name: 'Buscar componente' })).not.toBeInTheDocument()
    expect(navigation.getAllByRole('link')).toHaveLength(17)
    expect(navigation.getByRole('link', { name: 'Pestañas' })).toHaveAttribute('href', '#tabs')
    expect(screen.getByRole('region', { name: 'Estados de carga' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Reducir navegación' }))
    expect(screen.getByRole('button', { name: 'Expandir navegación' })).toHaveAttribute('aria-expanded', 'false')
    expect(screen.queryByRole('button', { name: 'Buscar componente' })).not.toBeInTheDocument()
    expect(navigation.getAllByRole('link')).toHaveLength(17)
  })
})
